# Suite 4: Contention Experiments (J0 - J3)
# ==============================================================================
async def benchmark_contention(
    base_url: str,
    model: str,
    results_dir: str,
    victim_prompt_len: int = 1024,
    victim_output_len: int = 256,
    attacker_prompt_len: int = 8192
) -> List[Dict[str, Any]]:
    print("\n" + "=" * 90)
    print("  SUITE 4: CONTENTION & ITL JITTER EXPERIMENTS (Simulating P/D Isolation)")
    print(f"  Victim Stream: Steady decode (1,024 prompt -> {victim_output_len} output)")
    print("  Attacker Burst: Bombardment with 8,192-token prefill requests")
    print("=" * 90)

    scenarios = [
        ("J0", None, "Decode only baseline (Zero interference)"),
        ("J1", 5.0, "Light contention: 1x 8K:1 prefill burst every 5.0 seconds"),
        ("J2", 1.0, "Heavy contention: 1x 8K:1 prefill burst every 1.0 second"),
        ("J3", 0.05, "Continuous saturation: Concurrent 8K:1 prefill bursts"),
    ]

    summary_rows = []
    baseline_p95_itl = 0.0

    victim_prompt = generate_token_prompt(victim_prompt_len, start_token=100)
    attacker_prompt = generate_token_prompt(attacker_prompt_len, start_token=5000)

    for case_id, burst_interval, desc in scenarios:
        logger.info(f"Running Contention Scenario {case_id}: {desc}")

        run_id = f"contention_{case_id}_{int(time.time())}"
        telemetry_path = os.path.join(results_dir, f"{run_id}_power.csv")
        telemetry = TelemetryCollector(telemetry_path)
        telemetry.start()

        stop_attack = asyncio.Event()

        async def attacker_loop():
            if burst_interval is None:
                return
            async with httpx.AsyncClient(timeout=120.0) as client:
                burst_cnt = 0
                while not stop_attack.is_set():
                    burst_cnt += 1
                    t_b0 = time.perf_counter()
                    try:
                        await client.post(
                            f"{base_url}/v1/completions",
                            json={"model": model, "prompt": attacker_prompt, "max_tokens": 1, "temperature": 0.0}
                        )
                        logger.debug(f"[{case_id}] Attacker prefill burst #{burst_cnt} completed in {time.perf_counter()-t_b0:.2f}s")
                    except Exception as e:
                        logger.debug(f"Attacker burst error: {e}")

                    if burst_interval > 0:
                        try:
                            await asyncio.wait_for(stop_attack.wait(), timeout=burst_interval)
                        except asyncio.TimeoutError:
                            pass
                    else:
                        await asyncio.sleep(0.01)

        # Launch attacker
        attacker_task = asyncio.create_task(attacker_loop())

        # Give attacker 0.5s head start if J3
        if case_id == "J3":
            await asyncio.sleep(0.5)

        # Run Victim Decode Stream
        async with httpx.AsyncClient(timeout=180.0) as client:
            victim_res = await run_single_streaming_request(
                client=client,
                base_url=base_url,
                model=model,
                prompt_tokens=victim_prompt,
                max_output_tokens=victim_output_len,
                request_id=f"victim_{case_id}"
            )

        stop_attack.set()
        await attacker_task
        pwr_data = telemetry.stop()

        if not victim_res["success"]:
            logger.error(f"Victim stream failed in {case_id}: {victim_res.get('error')}")
            continue

        itls = victim_res.get("itls_ms", [])
        pct_itl = calculate_percentiles(itls)
        tpot = victim_res.get("tpot_ms", 0.0)
        ttft = victim_res.get("ttft_ms", 0.0)

        if case_id == "J0":
            baseline_p95_itl = pct_itl["p95"]
            delta_p95 = 0.0
            inflation = 1.0
        else:
            delta_p95 = pct_itl["p95"] - baseline_p95_itl
            inflation = (pct_itl["p95"] / baseline_p95_itl) if baseline_p95_itl > 0 else 1.0

        row = {
            "scenario": case_id,
            "description": desc,
            "ttft_ms": round(ttft, 2),
            "tpot_ms": round(tpot, 2),
            "itl_p50_ms": round(pct_itl["p50"], 2),
            "itl_p95_ms": round(pct_itl["p95"], 2),
            "itl_p99_ms": round(pct_itl["p99"], 2),
            "itl_max_ms": round(pct_itl["max"], 2),
            "delta_p95_ms": round(delta_p95, 2),
            "itl_inflation_ratio": round(inflation, 2),
            "avg_power_w": round(pwr_data.get("avg_power_w", 0.0), 1)
        }
        summary_rows.append(row)

    print("\n" + "-" * 115)
    print(f"{'Scenario':<10} | {'ITL p50 (ms)':<14} | {'ITL p95 (ms)':<14} | {'ITL p99 (ms)':<14} | {'ITL Max (ms)':<14} | {'Delta p95':<12} | {'Inflation':<12} | {'Power':<8}")
    print("-" * 115)
    for r in summary_rows:
        delta_str = f"+{r['delta_p95_ms']:.1f} ms" if r['delta_p95_ms'] > 0 else "0.0 ms"
        infl_str = f"{r['itl_inflation_ratio']:.2f}x"
        print(f"{r['scenario']:<10} | {r['itl_p50_ms']:<14.2f} | {r['itl_p95_ms']:<14.2f} | {r['itl_p99_ms']:<14.2f} | {r['itl_max_ms']:<14.2f} | {delta_str:<12} | {infl_str:<12} | {r['avg_power_w']:<6.1f} W")
    print("-" * 115)
    return summary_rows


