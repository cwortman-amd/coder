# Suite 3: Concurrency Sweep (C = 1, 2, 4, 8, 16 on 8K:1K)
# ==============================================================================
async def benchmark_concurrency(
    base_url: str,
    model: str,
    results_dir: str,
    prompt_len: int = 8192,
    output_len: int = 1024,
    concurrency_levels: List[int] = [1, 2, 4, 8, 16]
) -> List[Dict[str, Any]]:
    print("\n" + "=" * 90)
    print("  SUITE 3: CONCURRENCY SWEEP (Anchor Workload: 8,192 In -> 1,024 Out)")
    print("  Quantifies throughput scaling, queue delay, and per-stream TPOT degradation")
    print("=" * 90)

    summary_rows = []

    for C in concurrency_levels:
        # Scale requests appropriately (at least 2*C for small, max 16 to keep test bounded)
        total_requests = min(C * 2, 16)
        logger.info(f"Running Concurrency C={C} ({total_requests} requests total)...")

        run_id = f"concurrency_c{C}_{int(time.time())}"
        telemetry_path = os.path.join(results_dir, f"{run_id}_power.csv")
        telemetry = TelemetryCollector(telemetry_path)
        telemetry.start()

        sem = asyncio.Semaphore(C)
        prompt = generate_token_prompt(prompt_len)
        results = []

        m_before = await fetch_vllm_metrics(base_url)
        t_global_start = time.perf_counter()

        async def worker(idx: int):
            async with sem:
                async with httpx.AsyncClient(timeout=240.0) as client:
                    res = await run_single_streaming_request(
                        client=client,
                        base_url=base_url,
                        model=model,
                        prompt_tokens=prompt,
                        max_output_tokens=output_len,
                        request_id=f"c{C}_r{idx}"
                    )
                    results.append(res)

        tasks = [worker(i) for i in range(total_requests)]
        await asyncio.gather(*tasks)

        t_global_end = time.perf_counter()
        total_duration = t_global_end - t_global_start
        pwr_data = telemetry.stop()
        m_after = await fetch_vllm_metrics(base_url)

        successful = [r for r in results if r.get("success")]
        if not successful:
            logger.error(f"All requests failed at C={C}")
            continue

        total_gen_tokens = sum(r["output_tokens"] for r in successful)
        aggregate_tok_s = total_gen_tokens / total_duration if total_duration > 0 else 0.0

        ttfts = [r["ttft_ms"] for r in successful]
        tpots = [r["tpot_ms"] for r in successful]
        pct_ttft = calculate_percentiles(ttfts)
        pct_tpot = calculate_percentiles(tpots)

        avg_power = pwr_data.get("avg_power_w", 0.0)
        total_energy_j = energy_from_pwr(pwr_data, total_duration)
        joules_per_tok = total_energy_j / (total_gen_tokens + (len(successful) * prompt_len)) if total_gen_tokens > 0 else 0.0
        kv_usage = kv_usage_pct(m_after.get("vllm:kv_cache_usage_perc", 0.0))

        row = {
            "concurrency": C,
            "requests": len(successful),
            "duration_s": round(total_duration, 2),
            "aggregate_tok_s": round(aggregate_tok_s, 2),
            "ttft_p50_ms": round(pct_ttft["p50"], 2),
            "ttft_p95_ms": round(pct_ttft["p95"], 2),
            "tpot_p50_ms": round(pct_tpot["p50"], 2),
            "tpot_p95_ms": round(pct_tpot["p95"], 2),
            "kv_cache_usage_pct": round(kv_usage, 1),
            "avg_power_w": round(avg_power, 1),
            "joules_per_token": round(joules_per_tok, 5)
        }
        summary_rows.append(row)

    print("\n" + "-" * 115)
    print(f"{'C':<4} | {'Aggr tok/s':<12} | {'TTFT p50 (ms)':<14} | {'TTFT p95 (ms)':<14} | {'TPOT p50 (ms)':<14} | {'TPOT p95 (ms)':<14} | {'KV %':<8} | {'Power':<8} | {'J/tok':<10}")
    print("-" * 115)
    for r in summary_rows:
        print(f"{r['concurrency']:<4} | {r['aggregate_tok_s']:<12.1f} | {r['ttft_p50_ms']:<14.1f} | {r['ttft_p95_ms']:<14.1f} | {r['tpot_p50_ms']:<14.1f} | {r['tpot_p95_ms']:<14.1f} | {r['kv_cache_usage_pct']:<8.1f} | {r['avg_power_w']:<6.1f} W | {r['joules_per_token']:<10.5f}")
    print("-" * 115)
    return summary_rows


