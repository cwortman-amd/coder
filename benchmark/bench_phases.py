# Suite 1: Prefill-Dominant Benchmark (P1 - P6)
# ==============================================================================
async def benchmark_prefill(
    base_url: str,
    model: str,
    results_dir: str,
    trials_per_case: int = 15,
    warmup_trials: int = 3
) -> List[Dict[str, Any]]:
    print("\n" + "=" * 90)
    print("  SUITE 1: PREFILL-DOMINANT BENCHMARK (Long Input + 1 Output Token)")
    print("  Approximates prompt ingestion capacity, TTFT scaling, and prefill tok/s")
    print("=" * 90)

    prefill_cases = [
        ("P1", 128, "Short prompt floor / launch"),
        ("P2", 1024, "Typical interactive prompt"),
        ("P3", 4096, "Moderate RAG / code context"),
        ("P4", 8192, "Primary coding-agent target"),
        ("P5", 12288, "Max supported single-card context limit"),
        ("P6", 16384, "Capacity boundary test (Expected HTTP 400 at 12K limit)"),
    ]

    summary_rows = []

    for case_id, in_len, desc in prefill_cases:
        logger.info(f"Executing Case {case_id} ({in_len} tokens, max_tokens=1): {desc}")

        # Warmup
        prompt = generate_token_prompt(in_len)
        async with httpx.AsyncClient(timeout=120.0) as client:
            for _ in range(warmup_trials):
                try:
                    await client.post(
                        f"{base_url}/v1/completions",
                        json={"model": model, "prompt": prompt, "max_tokens": 1, "temperature": 0.0}
                    )
                except Exception:
                    pass

        # Check if capacity limit reached
        test_resp = None
        async with httpx.AsyncClient(timeout=120.0) as client:
            try:
                r = await client.post(
                    f"{base_url}/v1/completions",
                    json={"model": model, "prompt": prompt, "max_tokens": 1, "temperature": 0.0}
                )
                if r.status_code != 200:
                    logger.warning(f"Case {case_id} ({in_len} tokens) blocked by engine: {r.status_code} - {r.text[:120]}")
                    summary_rows.append({
                        "case": case_id,
                        "input_tokens": in_len,
                        "status": f"BLOCKED ({r.status_code} Capacity Limit)",
                        "prompt_tok_s": 0.0,
                        "ttft_p50_ms": 0.0,
                        "ttft_p95_ms": 0.0,
                        "avg_power_w": 0.0,
                        "joules_per_tok": 0.0
                    })
                    continue
            except Exception as e:
                logger.warning(f"Case {case_id} failed: {e}")
                continue

        # Telemetry setup
        run_id = f"prefill_{case_id}_{in_len}_{int(time.time())}"
        telemetry_path = os.path.join(results_dir, f"{run_id}_power.csv")
        telemetry = TelemetryCollector(telemetry_path)
        telemetry.start()

        m_before = await fetch_vllm_metrics(base_url)
        ttfts_ms = []
        durations_s = []

        async with httpx.AsyncClient(timeout=120.0) as client:
            for trial in range(trials_per_case):
                t0 = time.perf_counter()
                try:
                    res = await client.post(
                        f"{base_url}/v1/completions",
                        json={"model": model, "prompt": prompt, "max_tokens": 1, "temperature": 0.0}
                    )
                    t1 = time.perf_counter()
                    if res.status_code == 200:
                        dur = t1 - t0
                        durations_s.append(dur)
                        ttfts_ms.append(dur * 1000.0)
                except Exception as e:
                    logger.warning(f"Trial {trial} error: {e}")

        pwr_data = telemetry.stop()
        m_after = await fetch_vllm_metrics(base_url)

        if not ttfts_ms:
            continue

        pct = calculate_percentiles(ttfts_ms)
        median_dur = pct["p50"] / 1000.0
        prompt_tok_s = in_len / median_dur if median_dur > 0 else 0.0

        # Engine internal metrics delta
        prefill_sum_delta = m_after.get("vllm:request_prefill_time_seconds_sum", 0) - m_before.get("vllm:request_prefill_time_seconds_sum", 0)
        prefill_cnt_delta = m_after.get("vllm:request_prefill_time_seconds_count", 0) - m_before.get("vllm:request_prefill_time_seconds_count", 0)
        engine_prefill_s = (prefill_sum_delta / prefill_cnt_delta) if prefill_cnt_delta > 0 else median_dur

        avg_power = pwr_data.get("avg_power_w", 0.0)
        energy_per_req = energy_from_pwr(pwr_data, median_dur * max(1, len(ttfts_ms))) / max(1, len(ttfts_ms))
        joules_per_tok = energy_per_req / in_len if in_len > 0 else 0.0

        row = {
            "case": case_id,
            "input_tokens": in_len,
            "status": "PASS",
            "prompt_tok_s": round(prompt_tok_s, 1),
            "engine_prefill_s": round(engine_prefill_s, 3),
            "ttft_p50_ms": round(pct["p50"], 2),
            "ttft_p95_ms": round(pct["p95"], 2),
            "avg_power_w": round(avg_power, 1),
            "joules_per_tok": round(joules_per_tok, 5)
        }
        summary_rows.append(row)

    # Print Table
    print("\n" + "-" * 98)
    print(f"{'Case':<6} | {'Input Len':<10} | {'Status':<18} | {'Prompt tok/s':<14} | {'TTFT p50 (ms)':<14} | {'TTFT p95 (ms)':<14} | {'Avg Power':<10}")
    print("-" * 98)
    for r in summary_rows:
        if r["status"] == "PASS":
            print(f"{r['case']:<6} | {r['input_tokens']:<10} | {r['status']:<18} | {r['prompt_tok_s']:<14.1f} | {r['ttft_p50_ms']:<14.2f} | {r['ttft_p95_ms']:<14.2f} | {r['avg_power_w']:<10.1f} W")
        else:
            print(f"{r['case']:<6} | {r['input_tokens']:<10} | {r['status']:<18} | {'N/A':<14} | {'N/A':<14} | {'N/A':<14} | {'N/A':<10}")
    print("-" * 98)
    return summary_rows


