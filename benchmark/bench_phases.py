def energy_from_pwr(pwr_data: Dict[str, Any], duration_s: float) -> float:
    for key in ("total_energy_joules", "energy_joules"):
        val = pwr_data.get(key)
        if val:
            return float(val)
    return float(pwr_data.get("avg_power_w", 0.0) or 0.0) * duration_s


def kv_usage_pct(raw: float) -> float:
    if raw is None:
        return 0.0
    return raw * 100.0 if raw <= 1.0 else raw


def calculate_percentiles(values: List[float]) -> Dict[str, float]:
    if not values:
        return {"p50": 0.0, "p95": 0.0, "p99": 0.0, "mean": 0.0, "min": 0.0, "max": 0.0}
    sorted_vals = sorted(values)
    n = len(sorted_vals)
    def get_pct(pct):
        k = (n - 1) * (pct / 100.0)
        f = int(k)
        c = f + 1
        if c < n:
            return sorted_vals[f] + (k - f) * (sorted_vals[c] - sorted_vals[f])
        return sorted_vals[f]
    return {
        "p50": get_pct(50),
        "p95": get_pct(95),
        "p99": get_pct(99),
        "mean": statistics.mean(sorted_vals),
        "min": sorted_vals[0],
        "max": sorted_vals[-1]
    }


class TelemetryCollector:
    def __init__(self, output_path: str, gpu_id: int = 0, interval: float = 0.25):
        self.output_path = output_path
        self.gpu_id = gpu_id
        self.interval = interval
        self.proc: Optional[subprocess.Popen] = None

    def start(self):
        script = os.path.join(PROJECT_DIR, "scripts", "collect_amd_power.py")
        if not os.path.exists(script):
            logger.warning(f"Power telemetry script not found at {script}, skipping.")
            return
        os.makedirs(os.path.dirname(os.path.abspath(self.output_path)), exist_ok=True)
        cmd = [
            sys.executable, script,
            "--gpu", str(self.gpu_id),
            "--interval", str(self.interval),
            "--output", self.output_path
        ]
        self.proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        time.sleep(0.5)

    def stop(self) -> Dict[str, Any]:
        if not self.proc:
            return {"avg_power_w": 0.0, "peak_power_w": 0.0, "energy_joules": 0.0}
        try:
            self.proc.send_signal(signal.SIGINT)
            self.proc.wait(timeout=3.0)
        except Exception:
            try:
                self.proc.kill()
            except Exception:
                pass
        self.proc = None

        # Parse summary JSON if generated by collect_amd_power.py
        json_file = os.path.splitext(self.output_path)[0] + ".json"
        if os.path.exists(json_file):
            try:
                with open(json_file, "r") as f:
                    return json.load(f)
            except Exception:
                pass

        # Otherwise parse CSV
        if os.path.exists(self.output_path):
            powers = []
            try:
                with open(self.output_path, "r") as f:
                    lines = f.readlines()
                    for line in lines[1:]:
                        parts = line.strip().split(",")
                        if len(parts) >= 3:
                            try:
                                powers.append(float(parts[2]))
                            except ValueError:
                                pass
                if powers:
                    avg_p = statistics.mean(powers)
                    peak_p = max(powers)
                    duration = len(powers) * self.interval
                    return {
                        "avg_power_w": round(avg_p, 2),
                        "peak_power_w": round(peak_p, 2),
                        "energy_joules": round(avg_p * duration, 2),
                        "duration_s": round(duration, 2)
                    }
            except Exception as e:
                logger.warning(f"Failed parsing telemetry CSV: {e}")

        return {"avg_power_w": 0.0, "peak_power_w": 0.0, "energy_joules": 0.0}


async def fetch_vllm_metrics(base_url: str) -> Dict[str, float]:
    metrics_url = f"{base_url}/metrics"
    data = {}
    try:
        async with httpx.AsyncClient(timeout=5.0) as client:
            resp = await client.get(metrics_url)
            if resp.status_code == 200:
                for line in resp.text.splitlines():
                    if line.startswith("#"):
                        continue
                    m = re.match(r'^([a-zA-Z0-9_:]+)(?:\{[^}]*\})?\s+([0-9.eE+-]+)', line)
                    if m:
                        name, val = m.group(1), float(m.group(2))
                        data[name] = val
    except Exception as e:
        logger.debug(f"Metrics fetch error: {e}")
    return data


def generate_token_prompt(num_tokens: int, start_token: int = 100) -> List[int]:
    """Generates an exact deterministic list of integer token IDs."""
    # Modulo 32000 to remain within typical vocabulary boundaries
    return [(start_token + i) % 32000 for i in range(num_tokens)]


async def run_single_streaming_request(
    client: httpx.AsyncClient,
    base_url: str,
    model: str,
    prompt_tokens: List[int],
    max_output_tokens: int,
    request_id: str = "req"
) -> Dict[str, Any]:
    """
    Submits a streaming completion request and captures precise arrival timestamps
    for every individual token chunk.
    """
    url = f"{base_url}/v1/completions"
    payload = {
        "model": model,
        "prompt": prompt_tokens,
        "max_tokens": max_output_tokens,
        "temperature": 0.0,
        "stream": True
    }

    t_start = time.perf_counter()
    chunk_times: List[float] = []

    try:
        async with client.stream("POST", url, json=payload, timeout=180.0) as response:
            if response.status_code != 200:
                body = await response.aread()
                return {"success": False, "status_code": response.status_code, "error": body.decode("utf-8", "ignore")}

            async for line in response.aiter_lines():
                if sse_has_content(line):
                    t_chunk = time.perf_counter()
                    chunk_times.append(t_chunk)

    except Exception as e:
        return {"success": False, "error": str(e)}

    t_end = time.perf_counter()
    total_time = t_end - t_start
    num_generated = len(chunk_times)

    if num_generated == 0:
        return {
            "success": False,
            "error": "No tokens received",
            "total_time_s": total_time
        }

    ttft = chunk_times[0] - t_start
    decode_duration = chunk_times[-1] - chunk_times[0] if num_generated > 1 else 0.0

    # Calculate individual inter-token latencies
    itls = [
        (chunk_times[i] - chunk_times[i - 1]) * 1000.0  # ms
        for i in range(1, num_generated)
    ]

    tpot_ms = (decode_duration / (num_generated - 1) * 1000.0) if num_generated > 1 else 0.0
    decode_tok_s = ((num_generated - 1) / decode_duration) if decode_duration > 0 else 0.0

    return {
        "success": True,
        "request_id": request_id,
        "input_tokens": len(prompt_tokens),
        "output_tokens": num_generated,
        "total_time_s": total_time,
        "ttft_ms": ttft * 1000.0,
        "decode_duration_s": decode_duration,
        "tpot_ms": tpot_ms,
        "decode_tok_s": decode_tok_s,
        "itls_ms": itls
    }


