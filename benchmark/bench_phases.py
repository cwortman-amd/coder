async def benchmark_decode(
    base_url: str,
    model: str,
    results_dir: str,
    output_tokens: int = 1024,
    trials_per_case: int = 5
) -> List[Dict[str, Any]]:
    print("\n" + "=" * 90)
    print("  SUITE 2: DECODE-DOMINANT BENCHMARK (Context Footprint + 1,024 Output Tokens)")
    print("  Isolates steady-state autoregressive generation, TPOT, and per-token ITL")
    print("=" * 90)

    decode_cases = [
        ("D1", 128, "Near-empty KV context baseline"),
        ("D2", 1024, "Typical chat / session context"),
        ("D3", 4096, "Moderate context decode"),
        ("D4", 8192, "Primary long-context agent decode target"),
    ]

    summary_rows = []

    for case_id, in_len, desc in decode_cases:
        logger.info(f"Executing Case {case_id} ({in_len} context -> {output_tokens} output tokens): {desc}")

        run_id = f"decode_{case_id}_{in_len}_{output_tokens}_{int(time.time())}"
        telemetry_path = os.path.join(results_dir, f"{run_id}_power.csv")
        telemetry = TelemetryCollector(telemetry_path)
        telemetry.start()

        prompt = generate_token_prompt(in_len)
        results = []

        async with httpx.AsyncClient(timeout=180.0) as client:
            for trial in range(trials_per_case):
                res = await run_single_streaming_request(
                    client=client,
                    base_url=base_url,
                    model=model,
                    prompt_tokens=prompt,
                    max_output_tokens=output_tokens,
                    request_id=f"{case_id}_t{trial}"
                )
                if res["success"]:
                    results.append(res)
                else:
                    logger.warning(f"Trial {trial} failed: {res.get('error')}")

        pwr_data = telemetry.stop()

        if not results:
            continue

        ttfts = [r["ttft_ms"] for r in results]
        tpots = [r["tpot_ms"] for r in results]
        rates = [r["decode_tok_s"] for r in results]

        # Aggregate all individual token ITLs across all trials
        all_itls = []
        for r in results:
            all_itls.extend(r.get("itls_ms", []))

        pct_ttft = calculate_percentiles(ttfts)
        pct_tpot = calculate_percentiles(tpots)
        pct_itl = calculate_percentiles(all_itls)
        median_decode_tok_s = statistics.median(rates) if rates else 0.0

        avg_power = pwr_data.get("avg_power_w", 0.0)
        energy_per_tok = (avg_power * (pct_tpot["p50"] / 1000.0)) if pct_tpot["p50"] > 0 else 0.0

        row = {
            "case": case_id,
            "prompt_tokens": in_len,
            "output_tokens": output_tokens,
            "decode_tok_s": round(median_decode_tok_s, 2),
            "tpot_p50_ms": round(pct_tpot["p50"], 2),
            "tpot_p95_ms": round(pct_tpot["p95"], 2),
            "itl_p50_ms": round(pct_itl["p50"], 2),
            "itl_p95_ms": round(pct_itl["p95"], 2),
            "itl_p99_ms": round(pct_itl["p99"], 2),
            "ttft_p50_ms": round(pct_ttft["p50"], 2),
            "avg_power_w": round(avg_power, 1),
            "joules_per_decode_tok": round(energy_per_tok, 4)
        }
        summary_rows.append(row)

    print("\n" + "-" * 110)
    print(f"{'Case':<6} | {'Prompt':<8} | {'Output':<8} | {'Decode tok/s':<14} | {'TPOT p50/p95 (ms)':<20} | {'ITL p95/p99 (ms)':<20} | {'TTFT p50 (ms)':<14} | {'Power':<8}")
    print("-" * 110)
    for r in summary_rows:
        tpot_str = f"{r['tpot_p50_ms']:.1f} / {r['tpot_p95_ms']:.1f}"
        itl_str = f"{r['itl_p95_ms']:.1f} / {r['itl_p99_ms']:.1f}"
        print(f"{r['case']:<6} | {r['prompt_tokens']:<8} | {r['output_tokens']:<8} | {r['decode_tok_s']:<14.2f} | {tpot_str:<20} | {itl_str:<20} | {r['ttft_p50_ms']:<14.1f} | {r['avg_power_w']:<6.1f} W")
    print("-" * 110)
    return summary_rows


